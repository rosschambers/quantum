async fn watch_themes() -> Result<(), Box<dyn std::error::Error>> {
    info!("Watching theme files for changes...");

    let themes_dir = PathBuf::from("frontend/themes");

    if !themes_dir.exists() {
        eprintln!("ERROR: frontend/themes directory not found");
        eprintln!("Please run from the project root directory");
        std::process::exit(1);
    }

    // Create a channel for watch events
    let (tx, rx) = mpsc::channel();

    // Create a watcher
    let mut watcher = watcher(tx, Duration::from_millis(500))?;
    watcher.watch(&themes_dir, RecursiveMode::Recursive)?;

    info!("Watching {} for changes", themes_dir.display());
    info!("Press Ctrl+C to stop");

    // Get socket path
    let socket_path = {
        let runtime_dir = std::env::var("XDG_RUNTIME_DIR")
            .unwrap_or_else(|_| format!("{}/.run", std::env::var("HOME").unwrap_or_default()));
        PathBuf::from(runtime_dir).join("quantum.sock")
    };

    // Watch for file changes
    loop {
        match rx.recv() {
            Ok(notify::DebouncedFileSystemEvent::Write(_)) |
            Ok(notify::DebouncedFileSystemEvent::Create(_)) |
            Ok(notify::DebouncedFileSystemEvent::Remove(_)) => {
                info!("Theme file changed, reloading...");
                
                // Try to connect to daemon and send reload command
                match send_reload(&socket_path).await {
                    Ok(_) => {
                        info!("Theme reload sent to daemon");
                    }
                    Err(e) => {
                        eprintln!("WARNING: Failed to send reload to daemon: {}", e);
                        eprintln!("Make sure quantumd is running");
                    }
                }
            }
            Ok(_) => {
                // Ignore other events
            }
            Err(e) => {
                eprintln!("Watch error: {}", e);
                break;
            }
        }
    }

    Ok(())
}

async fn send_reload(socket_path: &std::path::Path) -> Result<(), Box<dyn std::error::Error>> {
    // Connect to daemon socket
    let mut stream = UnixStream::connect(socket_path).await?;

    // Send theme.reload RPC call
    let request = json!({
        "jsonrpc": "2.0",
        "id": 1,
        "method": "theme.reload",
        "params": {}
    });

    let request_str = request.to_string() + "\n";
    stream.write_all(request_str.as_bytes()).await?;
    stream.flush().await?;

    Ok(())
}
