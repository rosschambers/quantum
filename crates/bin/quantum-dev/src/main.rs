use clap::{Parser, Subcommand};
use notify::{Watcher, RecursiveMode, watcher};
use std::path::PathBuf;
use std::sync::mpsc;
use std::time::Duration;
use serde_json::json;
use tokio::io::AsyncWriteExt;
use tokio::net::UnixStream;
use tracing::info;
use tracing_subscriber::EnvFilter;

#[derive(Parser)]
#[command(name = "quantum-dev")]
#[command(about = "Development utilities for quantum", long_about = None)]
struct Cli {
    #[command(subcommand)]
    command: Commands,
}

#[derive(Subcommand)]
enum Commands {
    /// Generate TypeScript bindings from Rust DTOs
    GenerateTs,
    /// Watch theme files and reload on changes
    Watch,
}

#[tokio::main]
async fn main() -> Result<(), Box<dyn std::error::Error>> {
    // Initialize tracing
    tracing_subscriber::fmt()
        .with_env_filter(EnvFilter::from_default_env())
        .init();

    let cli = Cli::parse();

    match cli.command {
        Commands::GenerateTs => generate_ts().await?,
        Commands::Watch => watch_themes().await?,
    }

    Ok(())
}

