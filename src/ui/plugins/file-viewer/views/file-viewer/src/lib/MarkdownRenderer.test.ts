function rect(partial: Partial<DOMRect>): DOMRect {
    return {
        x: 0,
        y: 0,
        width: 0,
        height: 0,
        top: 0,
        left: 0,
        right: 0,
        bottom: 0,
        toJSON() {
            return this;
        },
        ...partial,
    } as DOMRect;
}

